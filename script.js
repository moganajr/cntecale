function getSimulationResult(moduleId, values) {
  const config = simulationConfigs[moduleId];
  if (config.type === "loss") {
    const { harvest, lossRate } = config.baseline;
    const baselineLoss = harvest * lossRate / 100;
    const targetLoss = harvest * values.targetLossRate / 100;
    const recovered = Math.max(0, baselineLoss - targetLoss);
    const grossSales = recovered * values.salePrice;
    const addedCost = harvest * values.costPerHarvestKg;
    return [
      ["Baseline loss", `${baselineLoss.toFixed(1)} kg`],
      ["Modeled target loss", `${targetLoss.toFixed(1)} kg`],
      ["Additional saleable quantity", `${recovered.toFixed(1)} kg`],
      ["Estimated added gross sales", formatCurrency(grossSales)],
      ["Estimated added handling cost", formatCurrency(addedCost)],
      ["Balance before other costs", formatCurrency(grossSales - addedCost)]
    ];
  }

  if (config.type === "spread") {
    const spread = values.retail - values.farmGate;
    const knownCosts = values.transport + values.handling;
    return [
      ["Farm-gate to retail spread", `${formatCurrency(spread)}/kg`],
      ["Listed transport and handling", `${formatCurrency(knownCosts)}/kg`],
      ["Remainder before other costs and risk", `${formatCurrency(spread - knownCosts)}/kg`]
    ];
  }

  if (config.type === "sample") {
    const share = values.reporting / values.interviewed * 100;
    return [
      ["Interview sample", `${values.interviewed} farmers`],
      [config.sampleLabel || "Reporting transport difficulty", `${values.reporting} farmers`],
      ["Share of this sample", `${share.toFixed(1)}%`],
      ["Interpretation", "Describes this sample only"]
    ];
  }

  if (config.type === "systems") {
    const factors = [
      ["Climate and water", values.climate],
      ["Seed access and quality", values.seed],
      ["Labor and timing", values.labor],
      ["Road and market access", values.roads],
      ["Finance", values.finance],
      ["Extension access", values.extension]
    ].sort((first, second) => second[1] - first[1]);
    return [
      ["Highest current concern", factors[0][1] > 0 ? factors[0][0] : "None scored"],
      ["Next concern", factors[1][1] > 0 ? factors[1][0] : "None scored"],
      ["Evidence reminder", "Scores prioritize inquiry; they do not establish causes"]
    ];
  }

  if (config.type === "rootcause") {
    const score = (impact, evidence, feasibility) => evidence * 0.4 + impact * 0.35 + feasibility * 0.25;
    const firstScore = score(values.causeAImpact, values.causeAEvidence, values.causeAFeasibility);
    const secondScore = score(values.causeBImpact, values.causeBEvidence, values.causeBFeasibility);
    return [
      ["Hypothesis A inquiry score", `${firstScore.toFixed(2)}/5`],
      ["Hypothesis B inquiry score", `${secondScore.toFixed(2)}/5`],
      ["Higher current inquiry priority", firstScore >= secondScore ? "Hypothesis A" : "Hypothesis B"],
      ["Interpretation", "Priority for investigation, not a confirmed root cause"]
    ];
  }

  if (config.type === "risk") {
    const score = values.likelihood * values.impact;
    return [
      ["Illustrative risk score", `${score}/25`],
      ["Risk band", score >= 16 ? "High" : score >= 8 ? "Moderate" : "Lower"],
      ["Control feasibility", `${values.controlFeasibility}/5`],
      ["Interpretation", "Confirm ratings and response with local evidence"]
    ];
  }

  if (config.type === "enterprise") {
    const marketable = values.harvest * (1 - values.lossRate / 100);
    const grossRevenue = marketable * values.salePrice;
    const listedCosts = values.productionCosts + values.marketCosts;
    return [
      ["Estimated marketable quantity", `${marketable.toFixed(1)} kg`],
      ["Estimated gross revenue", formatCurrency(grossRevenue)],
      ["Entered costs", formatCurrency(listedCosts)],
      ["Balance before omitted costs and risk", formatCurrency(grossRevenue - listedCosts)]
    ];
  }

  if (config.type === "adoption") {
    const deviceReach = values.farmers * values.deviceRate / 100;
    const awareReach = deviceReach * values.awarenessRate / 100;
    const trialUsers = awareReach * values.useRate / 100;
    return [
      ["Potential device reach", `${deviceReach.toFixed(0)} farmers`],
      ["Potential awareness reach", `${awareReach.toFixed(0)} farmers`],
      ["Modeled trial users", `${trialUsers.toFixed(0)} farmers`],
      ["Estimated support cost", formatCurrency(trialUsers * values.supportCost)],
      ["Interpretation", "Scenario estimate, not an adoption forecast"]
    ];
  }

  if (config.type === "policy") {
    const score = (impact, inclusion, feasibility, cost) => impact * 0.35 + inclusion * 0.3 + feasibility * 0.25 + (6 - cost) * 0.1;
    const firstScore = score(values.optionAImpact, values.optionAInclusion, values.optionAFeasibility, values.optionACost);
    const secondScore = score(values.optionBImpact, values.optionBInclusion, values.optionBFeasibility, values.optionBCost);
    return [
      ["Option A weighted score", `${firstScore.toFixed(2)}/5`],
      ["Option B weighted score", `${secondScore.toFixed(2)}/5`],
      ["Higher current score", firstScore >= secondScore ? "Option A" : "Option B"],
      ["Weights", "Benefit 35%, inclusion 30%, feasibility 25%, lower cost 10%"]
    ];
  }

  if (config.type === "project") {
    const subtotal = values.production + values.water + values.training + values.market + values.monitoring;
    const contingency = subtotal * values.contingencyRate / 100;
    const total = subtotal + contingency;
    return [
      ["Estimated subtotal", formatCurrency(subtotal)],
      ["Contingency allowance", formatCurrency(contingency)],
      ["Estimated total", formatCurrency(total)],
      ["Estimated cost per beneficiary", formatCurrency(total / values.beneficiaries)]
    ];
  }

  if (config.type === "trial") {
    const yieldDifference = values.trialYield - values.baselineYield;
    const percentageChange = values.baselineYield > 0 ? yieldDifference / values.baselineYield * 100 : null;
    const grossDifference = yieldDifference * values.salePrice;
    return [
      ["Harvest difference", `${yieldDifference.toFixed(1)} kg`],
      ["Yield change", percentageChange === null ? "Baseline is zero" : `${percentageChange.toFixed(1)}%`],
      ["Estimated gross revenue difference", formatCurrency(grossDifference)],
      ["Balance after entered extra input cost", formatCurrency(grossDifference - values.extraCost)]
    ];
  }

  if (config.type === "budget") {
    const plannedSpending = values.stapleCost + values.vegetableCost + values.proteinCost;
    const remaining = values.budget - plannedSpending;
    return [
      ["Illustrative planned spending", formatCurrency(plannedSpending)],
      ["Available budget", formatCurrency(values.budget)],
      [remaining >= 0 ? "Amount remaining" : "Illustrative shortfall", formatCurrency(Math.abs(remaining))],
      ["Interpretation", "Budget scenario only; not a diet score"]
    ];
  }

  if (config.type === "cooperative") {
    const quantity = values.farmers * values.kgPerFarmer;
    const grossSales = quantity * values.salePrice;
    const listedCosts = values.transportCost + values.handlingCost;
    const remainder = grossSales - listedCosts;
    return [
      ["Pooled quantity", `${quantity.toFixed(0)} kg`],
      ["Estimated gross sales", formatCurrency(grossSales)],
      ["Listed group costs", formatCurrency(listedCosts)],
      ["Remainder before production and other costs", formatCurrency(remainder)],
      ["Remainder per participating farmer", formatCurrency(remainder / values.farmers)]
    ];
  }

  if (config.type === "disruption") {
    const routeSaleable = values.quantity * (1 - values.routeLossRate / 100);
    const waitSaleable = values.quantity * (1 - values.waitLossRate / 100);
    const routeBalance = routeSaleable * values.salePrice - values.routeCost;
    const waitBalance = waitSaleable * values.salePrice - values.storageCost;
    return [
      ["Alternate route: saleable quantity", `${routeSaleable.toFixed(1)} kg`],
      ["Alternate route: balance after entered route cost", formatCurrency(routeBalance)],
      ["Wait and store: saleable quantity", `${waitSaleable.toFixed(1)} kg`],
      ["Wait and store: balance after entered storage cost", formatCurrency(waitBalance)],
      ["Higher modeled balance", routeBalance >= waitBalance ? "Alternate route" : "Wait and store"]
    ];
  }

  const beforeRate = values.beforeLoss / values.beforeHarvest * 100;
  const afterRate = values.afterLoss / values.afterHarvest * 100;
  const percentagePointChange = beforeRate - afterRate;
  const relativeReduction = beforeRate > 0 ? percentagePointChange / beforeRate * 100 : 0;
  return [
    ["Before loss rate", `${beforeRate.toFixed(1)}%`],
    ["After loss rate", `${afterRate.toFixed(1)}%`],
    ["Reduction", `${percentagePointChange.toFixed(1)} percentage points`],
    ["Relative reduction", `${relativeReduction.toFixed(1)}%`]
  ];
}

