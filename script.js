function buildPortfolioMarkdown(learnerName, generatedAt = new Date()) {
  const totalLessons = courseData.reduce((sum, module) => sum + module.lessons.length, 0);
  const completedCount = state.completedLessons.size;
  const quizPassCount = Object.values(state.quizResults).filter((result) => result?.passed).length;
  const completedReflections = courseData.filter((module) => {
    const reflection = state.weeklyReflections[module.id];
    return activeCourse.reflectionPrompts?.length
      && activeCourse.reflectionPrompts.every(({ key }) => reflection?.[key]?.trim());
  }).length;
  const lines = [
    `# ${activeCourse.portfolioTitle}`,
    "",
    `**Learner:** ${learnerName || "Not provided"}`,
    `**Generated:** ${generatedAt.toISOString().slice(0, 10)}`,
    `**Lesson progress:** ${completedCount}/${totalLessons}`,
    `**Weekly quizzes passed:** ${quizPassCount}/${courseData.length}`,
    `**Learning points:** ${completedCount * 5 + quizPassCount * 20 + courseData.filter((module) => Array.isArray(state.caseChecks[module.id]) && state.caseChecks[module.id].filter(Boolean).length === 4).length * 10 + Object.values(state.simulationCompletions).filter(Boolean).length * 15 + (state.capstoneExported ? 30 : 0) + state.projectPhaseChecks.filter(Boolean).length * 10 + completedReflections * 5}`,
    ""
  ];

  if (activeCourse.assessments?.length) {
    lines.push("## Assessment score tracker");
    let earnedAssessmentPoints = 0;
    let recordedAssessmentWeight = 0;
    activeCourse.assessments.forEach((assessment, index) => {
      const score = state.assessmentScores[index];
      if (Number.isFinite(score)) {
        earnedAssessmentPoints += score;
        recordedAssessmentWeight += assessment.points;
        lines.push(`- ${assessment.title}: ${score}/${assessment.points} points`);
      } else {
        lines.push(`- ${assessment.title}: not recorded (${assessment.points} points possible)`);
      }
    });
    lines.push(`- Recorded total: ${earnedAssessmentPoints}/${recordedAssessmentWeight} weighted points; ${recordedAssessmentWeight}/100 weight recorded.`, "");
  }

  if (activeCourse.midtermPractice) {
    lines.push(`## ${activeCourse.midtermPractice.title} · Practice draft`);
    activeCourse.midtermPractice.questions.forEach((question) => {
      lines.push(`### ${question.label}`);
      lines.push(state.midtermResponses[question.key]?.trim() || "Not entered");
      lines.push("");
    });
    lines.push("Practice self-review rubric: no official score is assigned by this app.", "");
  }

  if (activeCourse.questionnaireBuilder) {
    lines.push("## Digital questionnaire design");
    lines.push(`Research question: ${state.questionnaireDraft.researchQuestion || "Not entered"}`, "");
    if (state.questionnaireDraft.questions.length) {
      state.questionnaireDraft.questions.forEach((question, index) => {
        lines.push(`${index + 1}. ${question.prompt || "Question prompt not entered"}`);
        lines.push(`   Response type: ${question.type}`);
        if (question.type === "multiple-choice") lines.push(`   Choices: ${question.options.join("; ") || "Not entered"}`);
      });
    } else {
      lines.push("No questions drafted yet.");
    }
    lines.push("");
  }

  if (activeCourse.symposiumReview) {
    lines.push("## Symposium peer review and author response");
    activeCourse.symposiumReview.prompts.forEach((prompt) => {
      lines.push(`### ${prompt.label}`);
      lines.push(state.symposiumReview[prompt.key]?.trim() || "Not entered");
      lines.push("");
    });
  }

  courseData.forEach((module) => {
    const lessonsCompleted = module.lessons.filter((lesson) => state.completedLessons.has(`${module.id}:${lesson.id}`)).length;
    const quizResult = state.quizResults[module.id];
    const reviewChecks = Array.isArray(state.caseChecks[module.id]) ? state.caseChecks[module.id].filter(Boolean).length : 0;
    lines.push(`## ${module.name}`);
    lines.push(`- Lessons completed: ${lessonsCompleted}/${module.lessons.length}`);
    lines.push(`- Quiz: ${quizResult ? `${quizResult.score}/${quizQuestions[module.id].length} (${quizResult.passed ? "passed" : "not passed"})` : "not attempted"}`);
    lines.push(`- Case self-review: ${reviewChecks}/4`);
    lines.push("");

    if (activeCourse.reflectionPrompts?.length) {
      const reflection = state.weeklyReflections[module.id] || {};
      lines.push("### SEC and OPD weekly reflection");
      activeCourse.reflectionPrompts.forEach(({ key, label }) => {
        lines.push(`**${label}**`);
        lines.push(reflection[key]?.trim() || "Not entered");
        lines.push("");
      });
    }

    if (state.caseNotes[module.id]?.trim()) {
      lines.push("### Case response");
      lines.push(state.caseNotes[module.id].trim());
      lines.push("");
    }

    if (module.id === "week2") {
      lines.push("### Anonymous field observations");
      if (state.fieldObservations.length) {
        state.fieldObservations.forEach((entry) => {
          lines.push(`- ${entry.date} | ${entry.county}, ${entry.community} | ${entry.actor} | ${entry.commodity} | ${entry.method} | Consent: ${entry.consent}`);
          if (entry.quantity) lines.push(`  - Quantity: ${entry.quantity} ${entry.unit}`);
          if (entry.observation) lines.push(`  - Finding: ${entry.observation}`);
        });
      } else {
        lines.push("No field observations recorded.");
      }
      lines.push("");
    }

    if (activeCourse.dataLab && module.id === "week3") {
      lines.push(`### ${activeCourse.dataLab.title}`);
      lines.push("Illustrative practice values, not field observations:");
      state.dataLabDraft.values.forEach((value, index) => {
        lines.push(`- Sample ${index + 1}: ${value === "" ? "missing" : `${value} ${activeCourse.dataLab.unit}`}`);
      });
      const summary = summarizeDataValues(state.dataLabDraft.values);
      lines.push(`- Summary: n=${summary.count}, missing=${summary.missing}, mean=${summary.mean?.toFixed(2) ?? "not available"}, median=${summary.median?.toFixed(2) ?? "not available"}`);
      lines.push("");
    }

    if (simulationConfigs[module.id]) {
      lines.push(`### ${simulationConfigs[module.id].title}`);
      if (state.simulationCompletions[module.id]) {
        const values = getSimulationValues(module.id);
        lines.push("- Status: logged");
        lines.push("- Inputs:");
        simulationConfigs[module.id].fields.forEach((field) => {
          lines.push(`  - ${field.label}: ${values[field.key]}`);
        });
        lines.push("- Results:");
        getSimulationResult(module.id, values).forEach(([label, result]) => {
          lines.push(`  - ${label}: ${result}`);
        });
      } else {
        lines.push("- Status: not logged");
      }
      lines.push("");
    }
  });

  lines.push("## Capstone project brief");
  if (Object.values(state.capstoneDraft).some((value) => String(value).trim())) {
    const fields = [
      ["Title", "title"],
      ["County", "county"],
      ["Community or market", "community"],
      ["Commodity or system", "commodity"],
      ["Problem", "problem"],
      ["Baseline evidence and source", "evidence"],
      ["Proposed intervention", "intervention"],
      ["Stakeholders and beneficiaries", "stakeholders"],
      ["Outcome indicator and target", "indicator"],
      ["Timeline and milestone", "timeline"],
      ["Risks and assumptions", "risks"]
    ];
    fields.push(...(activeCourse.capstoneExtraFields || []).map((field) => [field.label, field.key]));
    fields.forEach(([label, key]) => {
      lines.push(`### ${label}`);
      lines.push(state.capstoneDraft[key]?.trim() || "Not entered");
      lines.push("");
    });
  } else {
    lines.push("No capstone draft entered.");
  }

  lines.push("", "## Saved lessons");
  const bookmarkedLessons = state.bookmarks.map((bookmark) => {
    const [moduleId, lessonId] = bookmark.split(":");
    const module = courseData.find((item) => item.id === moduleId);
    const lesson = module?.lessons.find((item) => item.id === lessonId);
    return lesson ? `- ${module.name}: ${lesson.title}` : null;
  }).filter(Boolean);
  lines.push(...(bookmarkedLessons.length ? bookmarkedLessons : ["No lessons saved."]));

  if (activeCourse.projectMilestones?.length) {
    lines.push("", "## Continuous project milestones");
    activeCourse.projectMilestones.forEach((milestone, index) => {
      lines.push(`- [${state.projectPhaseChecks[index] ? "x" : " "}] ${milestone.phase}: ${milestone.output}`);
    });
  }

  lines.push("---", "Confirm calculations and assumptions against local evidence before sharing or implementation.");
  return lines.join("\n");
}

function findLessons(query) {
  const normalizedQuery = query.trim().toLocaleLowerCase();
  if (!normalizedQuery) return [];
  return courseData.flatMap((module, moduleIndex) => module.lessons
    .map((lesson, lessonIndex) => ({ module, moduleIndex, lesson, lessonIndex }))
    .filter(({ module, lesson }) => `${module.name} ${lesson.title} ${lesson.objective} ${lesson.summary}`.toLocaleLowerCase().includes(normalizedQuery)));
}

