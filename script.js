function summarizeDataValues(values) {
  const valid = values.flatMap((value) => {
    if (value === "" || value === null || value === undefined) return [];
    const numeric = Number(value);
    return Number.isFinite(numeric) && numeric >= 0 ? [numeric] : [];
  }).sort((first, second) => first - second);
  if (!valid.length) return { count: 0, missing: values.length, mean: null, median: null, min: null, max: null };
  const middle = Math.floor(valid.length / 2);
  const median = valid.length % 2 ? valid[middle] : (valid[middle - 1] + valid[middle]) / 2;
  return {
    count: valid.length,
    missing: values.length - valid.length,
    mean: valid.reduce((sum, value) => sum + value, 0) / valid.length,
    median,
    min: valid[0],
    max: valid[valid.length - 1]
  };
}

