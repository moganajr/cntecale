document.getElementById("exportProgressBackup").addEventListener("click", () => {
  const backup = {
    format: progressBackupFormat,
    version: progressBackupVersion,
    courseId: activeCourseId,
    exportedAt: new Date().toISOString(),
    progress: serializeProgressData()
  };
  const downloadUrl = URL.createObjectURL(new Blob([JSON.stringify(backup, null, 2)], { type: "application/json" }));
  const downloadLink = document.createElement("a");
  downloadLink.href = downloadUrl;
  downloadLink.download = `${activeCourseId.toLowerCase()}-progress-backup.json`;
  document.body.append(downloadLink);
  downloadLink.click();
  downloadLink.remove();
  window.setTimeout(() => URL.revokeObjectURL(downloadUrl), 1000);
  document.getElementById("backupStatus").textContent = "Progress backup downloaded.";
});

const progressBackupFile = document.getElementById("progressBackupFile");
document.getElementById("chooseProgressBackup").addEventListener("click", () => progressBackupFile.click());
progressBackupFile.addEventListener("change", async () => {
  const file = progressBackupFile.files[0];
  const status = document.getElementById("backupStatus");
  if (!file) return;
  if (file.size > 2 * 1024 * 1024) {
    status.textContent = "Backup file is too large. Select a file smaller than 2 MB.";
    progressBackupFile.value = "";
    return;
  }

  try {
    const backup = JSON.parse(await file.text());
    if (backup?.format !== progressBackupFormat || backup.version !== progressBackupVersion || backup.courseId !== activeCourseId) {
      throw new Error(`This is not a supported ${activeCourseId} progress backup.`);
    }
    if (!window.confirm("Restoring this backup will replace the course progress saved in this browser. Continue?")) {
      status.textContent = "Restore cancelled; current progress is unchanged.";
      return;
    }
    const restoredProgress = normalizeProgressData(backup.progress);
    if (!saveProgress(restoredProgress)) {
      status.textContent = "Could not restore backup because browser storage is unavailable or full.";
      return;
    }
    Object.assign(state, restoredProgress);
    status.textContent = "Backup restored. Reloading the course.";
    window.location.reload();
  } catch (error) {
    status.textContent = error instanceof SyntaxError ? "Could not read that JSON backup file." : error.message;
  } finally {
    progressBackupFile.value = "";
  }
});

if ("serviceWorker" in navigator) {
  window.addEventListener("load", () => {
    navigator.serviceWorker.register("./service-worker.js").catch(() => {});
  });
}

