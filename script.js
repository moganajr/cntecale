function normalizeProgressData(saved) {
  const raw = saved && typeof saved === "object" && !Array.isArray(saved) ? saved : {};
  const moduleIds = new Set(courseData.map((module) => module.id));
  const lessonKeys = new Set(courseData.flatMap((module) => module.lessons.map((lesson) => `${module.id}:${lesson.id}`)));
  const completedLessons = new Set(Array.isArray(raw.completedLessons)
    ? raw.completedLessons.filter((key) => typeof key === "string" && lessonKeys.has(key))
    : []);
  const quizAnswers = {};
  const quizResults = {};
  const caseNotes = {};
  const caseChecks = {};
  const weeklyReflections = {};
  const assessmentScores = {};
  const midtermResponses = {};
  const symposiumReview = {};
  const questionnaireDraft = { researchQuestion: "", questions: [] };
  const dataLabDraft = { values: [...(activeCourse.dataLab?.initialValues || [])] };
  const projectPhaseChecks = [];
  const simulationInputs = {};
  const simulationCompletions = {};

  for (const module of courseData) {
    const moduleId = module.id;
    const questions = quizQuestions[moduleId];
    const savedAnswers = raw.quizAnswers?.[moduleId];
    if (savedAnswers && typeof savedAnswers === "object" && !Array.isArray(savedAnswers)) {
      quizAnswers[moduleId] = Object.fromEntries(Object.entries(savedAnswers).flatMap(([questionIndex, optionIndex]) => {
        const index = Number(questionIndex);
        return Number.isInteger(index) && index >= 0 && index < questions.length
          && Number.isInteger(optionIndex) && optionIndex >= 0 && optionIndex < questions[index].options.length
          ? [[String(index), optionIndex]]
          : [];
      }));
    }

    const result = raw.quizResults?.[moduleId];
    const answers = quizAnswers[moduleId] || {};
    const hasCompleteAnswers = questions.every((_, index) => Number.isInteger(answers[index]));
    const calculatedScore = hasCompleteAnswers
      ? questions.filter((question, index) => answers[index] === question.answer).length
      : -1;
    if (result && result.totalQuestions === questions.length && Number.isInteger(result.score)
      && result.score >= 0 && result.score <= questions.length && result.score === calculatedScore) {
      const passed = result.score >= Math.ceil(questions.length * 0.7);
      if (result.passed === passed) quizResults[moduleId] = { score: result.score, passed, totalQuestions: questions.length };
    }

    if (typeof raw.caseNotes?.[moduleId] === "string") caseNotes[moduleId] = raw.caseNotes[moduleId].slice(0, 10000);
    if (Array.isArray(raw.caseChecks?.[moduleId])) {
      caseChecks[moduleId] = Array.from({ length: 4 }, (_, index) => raw.caseChecks[moduleId][index] === true);
    }
    const reflection = raw.weeklyReflections?.[moduleId];
    if (reflection && typeof reflection === "object" && !Array.isArray(reflection)) {
      weeklyReflections[moduleId] = Object.fromEntries((activeCourse.reflectionPrompts || []).flatMap(({ key }) =>
        typeof reflection[key] === "string" ? [[key, reflection[key].slice(0, 1200)]] : []
      ));
    }

    const config = simulationConfigs[moduleId];
    const inputs = raw.simulationInputs?.[moduleId];
    if (config && inputs && typeof inputs === "object" && !Array.isArray(inputs)) {
      const validInputs = {};
      for (const field of config.fields) {
        const value = inputs[field.key];
        if (Number.isFinite(value) && value >= field.min && value <= field.max) validInputs[field.key] = value;
      }
      if (Object.keys(validInputs).length) simulationInputs[moduleId] = validInputs;
    }
    if (config && raw.simulationCompletions?.[moduleId] === true
      && config.fields.every((field) => Number.isFinite(simulationInputs[moduleId]?.[field.key]))) {
      simulationCompletions[moduleId] = true;
    }
  }

  const observationMethods = ["Direct observation", "Key-informant interview", "Focus group", "Public record review"];
  const actors = ["Farmer", "Trader", "Processor", "Transporter", "Consumer or household", "Extension or community organization", "Other group"];
  const units = ["kg", "g", "basket", "sack", "crate", "other"];
  const fieldObservations = Array.isArray(raw.fieldObservations) ? raw.fieldObservations.slice(0, 100).flatMap((entry, index) => {
    if (!entry || typeof entry !== "object" || !liberianCounties.includes(entry.county)
      || typeof entry.community !== "string" || !entry.community.trim() || entry.community.length > 100
      || typeof entry.date !== "string" || !/^\d{4}-\d{2}-\d{2}$/.test(entry.date)
      || new Date(`${entry.date}T00:00:00Z`).toISOString().slice(0, 10) !== entry.date
      || !actors.includes(entry.actor) || typeof entry.commodity !== "string" || entry.commodity.length > 100
      || !observationMethods.includes(entry.method)
      || !["yes", "no", "not-applicable"].includes(entry.consent)
      || (["Key-informant interview", "Focus group"].includes(entry.method) && entry.consent !== "yes")
      || (entry.quantity !== "" && (!Number.isFinite(Number(entry.quantity)) || Number(entry.quantity) < 0))
      || !units.includes(entry.unit) || typeof entry.observation !== "string" || entry.observation.length > 800) return [];
    return [{
      id: `restored-${index}`,
      date: entry.date,
      county: entry.county,
      community: entry.community.trim(),
      actor: entry.actor,
      commodity: entry.commodity,
      method: entry.method,
      consent: entry.consent,
      quantity: entry.quantity === "" ? "" : String(Number(entry.quantity)),
      unit: entry.unit,
      observation: entry.observation
    }];
  }) : [];

  const capstoneFields = { title: 100, county: 100, community: 100, commodity: 100, problem: 600, evidence: 800, intervention: 800, stakeholders: 600, indicator: 250, timeline: 250, risks: 800 };
  (activeCourse.capstoneExtraFields || []).forEach(({ key, maxLength }) => { capstoneFields[key] = maxLength; });
  const capstoneDraft = {};
  for (const [key, maxLength] of Object.entries(capstoneFields)) {
    const value = raw.capstoneDraft?.[key];
    if (typeof value === "string") capstoneDraft[key] = value.slice(0, maxLength);
  }
  if (!liberianCounties.includes(capstoneDraft.county)) delete capstoneDraft.county;
  if (!courseCommodities.includes(capstoneDraft.commodity)) delete capstoneDraft.commodity;
  const capstoneExported = raw.capstoneExported === true;
  const bookmarks = Array.isArray(raw.bookmarks)
    ? [...new Set(raw.bookmarks.filter((bookmark) => typeof bookmark === "string" && lessonKeys.has(bookmark)))]
    : [];
  projectPhaseChecks.push(...Array.from({ length: activeCourse.projectMilestones?.length || 0 }, (_, index) => raw.projectPhaseChecks?.[index] === true));
  (activeCourse.assessments || []).forEach((assessment, index) => {
    const score = raw.assessmentScores?.[index];
    if (Number.isFinite(score) && score >= 0 && score <= assessment.points) assessmentScores[index] = score;
  });
  if (activeCourse.midtermPractice) {
    for (const { key } of activeCourse.midtermPractice.questions) {
      const response = raw.midtermResponses?.[key];
      if (typeof response === "string") midtermResponses[key] = response.slice(0, 2500);
    }
  }
  if (activeCourse.symposiumReview) {
    for (const { key, maxLength } of activeCourse.symposiumReview.prompts) {
      const response = raw.symposiumReview?.[key];
      if (typeof response === "string") symposiumReview[key] = response.slice(0, maxLength);
    }
  }
  if (activeCourse.questionnaireBuilder) {
    const draft = raw.questionnaireDraft;
    if (draft && typeof draft === "object" && !Array.isArray(draft)) {
      if (typeof draft.researchQuestion === "string") questionnaireDraft.researchQuestion = draft.researchQuestion.slice(0, 600);
      const allowedTypes = new Set(["text", "number", "yes-no", "multiple-choice"]);
      questionnaireDraft.questions = Array.isArray(draft.questions)
        ? draft.questions.flatMap((question) => {
          if (!question || typeof question !== "object" || typeof question.prompt !== "string" || !allowedTypes.has(question.type)) return [];
          return [{
            prompt: question.prompt.slice(0, 250),
            type: question.type,
            options: Array.isArray(question.options)
              ? question.options.filter((option) => typeof option === "string" && option.trim()).slice(0, 8).map((option) => option.slice(0, 120))
              : []
          }];
        }).slice(0, activeCourse.questionnaireBuilder.maxQuestions)
        : [];
    }
  }
  if (activeCourse.dataLab && Array.isArray(raw.dataLabDraft?.values)) {
    dataLabDraft.values = raw.dataLabDraft.values.slice(0, activeCourse.dataLab.maxRows).map((value) => {
      if (value === "") return "";
      const number = Number(value);
      return Number.isFinite(number) && number >= 0 && number <= activeCourse.dataLab.maxValue ? String(number) : "";
    });
  }

  return { completedLessons, quizAnswers, quizResults, caseNotes, caseChecks, weeklyReflections, assessmentScores, midtermResponses, symposiumReview, questionnaireDraft, dataLabDraft, simulationInputs, simulationCompletions, capstoneDraft, capstoneExported, fieldObservations, bookmarks, projectPhaseChecks };
}

function loadProgress() {
  try {
    const saved = JSON.parse(localStorage.getItem(getProgressStorageKey()) || "{}");
    return normalizeProgressData(saved);
  } catch {
    return normalizeProgressData({});
  }
}

function serializeProgressData(progress = state) {
  return {
    completedLessons: [...progress.completedLessons],
    quizAnswers: progress.quizAnswers,
    quizResults: progress.quizResults,
    caseNotes: progress.caseNotes,
    caseChecks: progress.caseChecks,
    weeklyReflections: progress.weeklyReflections,
    assessmentScores: progress.assessmentScores,
    midtermResponses: progress.midtermResponses,
    symposiumReview: progress.symposiumReview,
    questionnaireDraft: progress.questionnaireDraft,
    dataLabDraft: progress.dataLabDraft,
    simulationInputs: progress.simulationInputs,
    simulationCompletions: progress.simulationCompletions,
    capstoneDraft: progress.capstoneDraft,
    capstoneExported: progress.capstoneExported,
    fieldObservations: progress.fieldObservations,
    bookmarks: progress.bookmarks,
    projectPhaseChecks: progress.projectPhaseChecks
  };
}

function saveProgress(progress = state) {
  try {
    localStorage.setItem(getProgressStorageKey(), JSON.stringify(serializeProgressData(progress)));
    return true;
  } catch {
    // Progress remains available for this session if browser storage is disabled.
    return false;
  }
}

