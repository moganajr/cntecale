function updateGamification() {
  const completedLessons = state.completedLessons.size;
  const passedQuizzes = Object.values(state.quizResults).filter((result) => result?.passed).length;
  const completedReviews = courseData.filter((module) =>
    Array.isArray(state.caseChecks[module.id]) && state.caseChecks[module.id].filter(Boolean).length === 4
  ).length;
  const completedSimulations = Object.values(state.simulationCompletions).filter(Boolean).length;
  const completedProjectMilestones = state.projectPhaseChecks.filter(Boolean).length;
  const completedReflections = courseData.filter((module) => {
    const reflection = state.weeklyReflections[module.id];
    return activeCourse.reflectionPrompts?.length
      && activeCourse.reflectionPrompts.every(({ key }) => reflection?.[key]?.trim());
  }).length;
  const points = completedLessons * 5 + passedQuizzes * 20 + completedReviews * 10 + completedSimulations * 15 + completedProjectMilestones * 10 + completedReflections * 5 + (state.capstoneExported ? 30 : 0);
  const rank = points >= 400 ? "Community champion" : points >= 250 ? "Food-systems strategist" : points >= 100 ? "Field analyst" : "Course explorer";
  const totalLessons = courseData.reduce((sum, module) => sum + module.lessons.length, 0);

  document.getElementById("pointsText").textContent = `${points}`;
  document.getElementById("rankText").textContent = rank;

  const badges = [
    { label: "First lesson", earned: completedLessons > 0 },
    { label: "Evidence reviewer", earned: completedReviews > 0 },
    { label: "Quiz passed", earned: passedQuizzes > 0 },
    { label: "Decision lab", earned: completedSimulations > 0 },
    { label: "Project milestone", earned: completedProjectMilestones > 0 },
    { label: "SEC reflection", earned: completedReflections > 0 },
    { label: "Capstone brief", earned: state.capstoneExported },
    { label: "Course complete", earned: completedLessons === totalLessons && passedQuizzes === courseData.length }
  ];
  document.getElementById("achievementBadges").innerHTML = badges
    .map((badge) => `<span class="achievement-badge ${badge.earned ? "is-earned" : ""}">${badge.label}</span>`)
    .join("");
}

function updateProgress() {
  const totalLessons = courseData.reduce((sum, module) => sum + module.lessons.length, 0);
  const completedCount = state.completedLessons.size;
  const percent = Math.round((completedCount / totalLessons) * 100);

  progressText.textContent = `${percent}%`;
  completedText.textContent = `${completedCount}/${totalLessons}`;
  progressBar.style.width = `${percent}%`;
  updateGamification();
}

function renderQuiz() {
  const module = getCurrentModule();
  const questions = quizQuestions[module.id];
  state.quizAnswers[module.id] ||= {};
  const answers = state.quizAnswers[module.id];
  const result = state.quizResults[module.id];

  document.getElementById("quizTitle").textContent = `${module.name.split(" · ")[0]} knowledge check`;
  quizContainer.innerHTML = `
    <div class="quiz-list">
      ${questions
        .map(
          (question, questionIndex) => `
            <div class="quiz-item">
              <h3>${questionIndex + 1}. ${question.question}</h3>
              <div class="option-list">
                ${question.options
                  .map(
                    (option, optionIndex) => `
                      <button class="option-btn ${answers[questionIndex] === optionIndex ? "selected" : ""}" aria-pressed="${answers[questionIndex] === optionIndex}" data-question-index="${questionIndex}" data-option-index="${optionIndex}">
                        ${option}
                      </button>
                    `
                  )
                  .join("")}
              </div>
            </div>
          `
        )
        .join("")}
    </div>
    ${result ? (() => {
      const missed = questions.map((question, questionIndex) => ({ question, questionIndex }))
        .filter(({ questionIndex }) => answers[questionIndex] !== questions[questionIndex].answer);
      return `
        <section class="quiz-feedback" aria-live="polite">
          <h3>${missed.length ? "Review and retry" : "All answers correct"}</h3>
          ${missed.length ? missed.map(({ question, questionIndex }) => {
            const lesson = module.lessons[Math.min(questionIndex, module.lessons.length - 1)];
            return `
              <article class="quiz-review-item">
                <p><strong>${question.question}</strong></p>
                <p>Your answer: ${question.options[answers[questionIndex]]}</p>
                <p>Correct answer: <strong>${question.options[question.answer]}</strong></p>
                <button class="secondary-btn review-lesson" type="button" data-lesson-index="${Math.min(questionIndex, module.lessons.length - 1)}">Review: ${lesson.title}</button>
              </article>
            `;
          }).join("") : "<p>Great work. You can revisit any lesson using search or bookmarks.</p>"}
        </section>
      `;
    })() : ""}
    <div class="quiz-actions">
      <button class="primary-btn" id="checkQuiz">Submit weekly quiz</button>
      <span class="score-box ${result ? (result.passed ? "is-passed" : "is-not-passed") : ""}" id="scoreBox" aria-live="polite">${result ? `Score: ${result.score}/${questions.length} · ${result.passed ? "Passed" : "Try again"}` : "Pass mark: 70%"}</span>
    </div>
  `;

  const optionButtons = quizContainer.querySelectorAll(".option-btn");
  optionButtons.forEach((button) => {
    button.addEventListener("click", () => {
      const questionIndex = Number(button.dataset.questionIndex);
      const optionIndex = Number(button.dataset.optionIndex);
      state.quizAnswers[module.id] ||= {};
      state.quizAnswers[module.id][questionIndex] = optionIndex;
      delete state.quizResults[module.id];
      moduleList.querySelector(`[data-module-index="${state.selectedModule}"] .module-quiz-status`).textContent = "Quiz not passed";
      quizContainer.querySelector(".quiz-feedback")?.remove();
      const scoreBox = document.getElementById("scoreBox");
      scoreBox.textContent = "Pass mark: 70%";
      scoreBox.classList.remove("is-passed", "is-not-passed");
      const parent = button.closest(".option-list");
      parent.querySelectorAll(".option-btn").forEach((item) => {
        item.classList.remove("selected");
        item.classList.remove("correct", "incorrect");
        item.setAttribute("aria-pressed", "false");
      });
      button.classList.add("selected");
      button.setAttribute("aria-pressed", "true");
      saveProgress();
      updateGamification();
    });
  });

  quizContainer.querySelectorAll(".review-lesson").forEach((button) => {
    button.addEventListener("click", () => {
      state.selectedLesson = Number(button.dataset.lessonIndex);
      renderEverything();
    });
  });

  document.getElementById("checkQuiz").addEventListener("click", () => {
    if (questions.some((question, index) => answers[index] === undefined)) {
      document.getElementById("scoreBox").textContent = "Answer every question before submitting.";
      return;
    }

    const score = questions.reduce((total, question, index) => total + (answers[index] === question.answer ? 1 : 0), 0);
    const passed = score >= Math.ceil(questions.length * 0.7);

    const buttons = quizContainer.querySelectorAll(".option-btn");
    buttons.forEach((button) => {
      const questionIndex = Number(button.dataset.questionIndex);
      const optionIndex = Number(button.dataset.optionIndex);
      const question = questions[questionIndex];
      const isCorrect = optionIndex === question.answer;
      const isSelected = answers[questionIndex] === optionIndex;

      if (isCorrect) button.classList.add("correct");
      if (isSelected && !isCorrect) button.classList.add("incorrect");
    });

    state.quizResults[module.id] = { score, passed, totalQuestions: questions.length };
    saveProgress();
    renderEverything();
  });
}

