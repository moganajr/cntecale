import assert from 'node:assert/strict';
import {makeClassroomState,enrollLearner,applyClassroomCommand,classroomSnapshot} from '../src/classroomCore.js';
import {TEACHING_SLIDES} from '../src/diagnosticMicroscopy.js';
let checks=0;const yes=(v,label)=>{assert.ok(v,label);checks++},eq=(a,b)=>{assert.deepEqual(a,b);checks++},fails=fn=>{assert.throws(fn);checks++};
const room=makeClassroomState({mode:'equipment',equipmentId:'field-microscope',teacherName:'Instructor'});
enrollLearner(room,'student-a','Learner Alpha');enrollLearner(room,'student-b','Learner Beta');
const a={role:'student',id:'student-a'},b={role:'student',id:'student-b'},lecturer={role:'lecturer'};
eq(classroomSnapshot(room,{role:'student',id:a.id}).participants.length,1);
eq(classroomSnapshot(room,{role:'student',id:a.id}).medicalParticipants[0].id,a.id);
eq(classroomSnapshot(room,{role:'lecturer'}).medicalParticipants.length,2);
fails(()=>applyClassroomCommand(room,a,{type:'pause',studentId:b.id,value:true}));
fails(()=>applyClassroomCommand(room,a,{type:'medical_demo_action',action:{kind:'ppe',value:true}}));
fails(()=>applyClassroomCommand(room,{role:'student',id:'unknown'},{type:'medical_action',action:{kind:'ppe',value:true}}));
let revision=room.revision;
applyClassroomCommand(room,a,{type:'medical_action',action:{kind:'ppe',value:true}});
eq(room.revision,revision+1);yes(room.learners.get(a.id).medical.ppe);eq(room.learners.get(b.id).medical.ppe,false);
applyClassroomCommand(room,b,{type:'medical_action',action:{kind:'ppe',value:true}});
applyClassroomCommand(room,b,{type:'medical_action',action:{kind:'slide-select',slide:'stain'}});
eq(room.learners.get(b.id).medical.microscopy.slide,'stain');
eq(room.learners.get(a.id).medical.microscopy.slide,'smear');
applyClassroomCommand(room,lecturer,{type:'medical_demo_action',action:{kind:'ppe',value:true}});
applyClassroomCommand(room,lecturer,{type:'medical_demo_action',action:{kind:'slide-select',slide:'tissue'}});
eq(room.medicalDemo.microscopy.slide,'tissue');eq(room.learners.get(a.id).medical.microscopy.slide,'smear');
applyClassroomCommand(room,lecturer,{type:'pause',studentId:b.id,value:true});
fails(()=>applyClassroomCommand(room,b,{type:'medical_action',action:{kind:'slide-focus',value:45}}));
applyClassroomCommand(room,a,{type:'medical_action',action:{kind:'slide-focus',value:43}});
eq(room.learners.get(a.id).medical.microscopy.focus,43);eq(room.learners.get(b.id).medical.microscopy.focus,0);
const feedback=applyClassroomCommand(room,lecturer,{type:'feedback',studentId:a.id,text:'Review focus'});
eq(feedback.feedback.studentId,a.id);
fails(()=>applyClassroomCommand(room,a,{type:'feedback',studentId:b.id,text:'spoof'}));
const beforeReset=room.revision;
applyClassroomCommand(room,lecturer,{type:'reset_learner',studentId:b.id});
eq(room.learners.get(b.id).locked,false);eq(room.learners.get(b.id).medical.microscopy.slide,'smear');
eq(room.learners.get(a.id).medical.microscopy.focus,43);
eq(room.revision,beforeReset+1);
let last=0;for(const event of room.events){yes(event.sequence>last,'events must be strictly ordered');last=event.sequence}
const chemistry=makeClassroomState({mode:'titration'});enrollLearner(chemistry,'c','Chemistry Student');
fails(()=>applyClassroomCommand(chemistry,{role:'student',id:'c'},{type:'medical_action',action:{kind:'ppe',value:true}}));
applyClassroomCommand(chemistry,{role:'student',id:'c'},{type:'action',action:{kind:'ppe',value:true}});
eq(chemistry.learners.get('c').bench.ppe,true);
eq(room.learners.get(a.id).bench.ppe,false);
eq(TEACHING_SLIDES.tissue.label.length>0,true);
console.log(checks+' classroom authorization, independent workbench and ordered-event assertions passed.');
